// MaxStepPolicies is the most steps with rules one policy may carry. Every
// step policy has to fit the bridge stamp, which carries it in 16 bits
// (bpf.StepStampPolicyMax; a firewall test pins the two equal), or a
// step's containers would get the job's rules alone.
const MaxStepPolicies = 0xFFFF

// StepConfig is one workflow step's own allow rules, added to the job's for
// that step's processes. The job's rules decide first, and a step's can only
// allow what they leave undecided, so a step never gets less than the job.
// Mode and the default action stay the job's, and a step has no deny rules.
type StepConfig struct {
	// ID is the step's `id:` in the workflow, as GITHUB_ACTION carries it.
	ID string `json:"id"`
	// Rules are allow rules; an omitted action means allow.
	Rules []Rule `json:"rules"`
}

// UnmarshalJSON decodes a step strictly: a key the schema doesn't know, in
// the step or in any of its rules, fails the load instead of being dropped.
// A misspelled "ports" would otherwise turn a port-scoped allow into an
// all-ports one.
func (s *StepConfig) UnmarshalJSON(data []byte) error {
	type plain StepConfig
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var p plain
	if err := dec.Decode(&p); err != nil {
		return fmt.Errorf("step: %w", err)
	}
	*s = StepConfig(p)
	return nil
}

// stepIDPattern is GitHub's syntax for a step id: a letter or an
// underscore, then letters, digits, hyphens and underscores.
var stepIDPattern = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_-]*$`)

// stepPolicy is one step's resolved allow tier: the policy its rules sit
// under in the rule maps, and the rules, matched on their own.
type stepPolicy struct {
	id     string
	policy uint32
	rules  []ResolvedRule
}

// compileSteps validates steps and resolves each one's rules under a policy
// of its own, numbered 1..N in config order among the steps that have rules
// (a step without rules adds nothing and gets none). Validation is strict: a
// bad step fails the load, like a bad rule. Step rules are normalized and
// merged in place, as the job's are.
//
// Under a default-allow job the steps are validated and then dropped, with a
// Warn: whatever the job's rules leave undecided is already allowed, so step
// rules would add nothing.
func compileSteps(steps []StepConfig, defaultAction Action) ([]stepPolicy, error) {
	seen := make(map[string]bool, len(steps))
	out := []stepPolicy{} // never nil: a load has happened (StepRulesKnown)
	for i := range steps {
		st := &steps[i]
		if err := validateStepID(st.ID); err != nil {
			return nil, fmt.Errorf("steps[%d]: %w", i, err)
		}
		// GitHub compares ids without case, so two that differ only in case
		// would name one step.
		folded := strings.ToLower(st.ID)
		if seen[folded] {
			return nil, fmt.Errorf("steps[%d]: duplicate step id %q", i, st.ID)
		}
		seen[folded] = true
		rules, err := compileStepRules(st)
		if err != nil {
			return nil, fmt.Errorf("step %q: %w", st.ID, err)
		}
		if len(rules) == 0 {
			continue
		}
		if len(out) == MaxStepPolicies {
			return nil, fmt.Errorf("more than %d steps with rules", MaxStepPolicies)
		}
		out = append(out, stepPolicy{id: st.ID, policy: uint32(len(out) + 1), rules: rules})
	}
	if len(out) > 0 && defaultAction == ActionAllow {
		slog.Warn("Ignoring step rules: the job's default action is allow, so they have nothing to add",
			"steps", len(out))
		return []stepPolicy{}, nil
	}
	return out, nil
}

// validateStepID checks an id against GitHub's syntax. Ids starting with
// "__" are the runner's own, generated for steps the workflow gave no id, so
// no rule may name one.
func validateStepID(id string) error {
	switch {
	case id == "":
		return fmt.Errorf("step id is empty")
	case strings.HasPrefix(id, "__"):
		return fmt.Errorf("step id %q: ids starting with __ are generated by the runner", id)
	case !stepIDPattern.MatchString(id):
		return fmt.Errorf("step id %q: must start with a letter or _ and hold only letters, digits, - and _", id)
	}
	return nil
}

// compileStepRules checks one step's rules, runs them through the job's
// normalize, validate and merge, and resolves them.
func compileStepRules(st *StepConfig) ([]ResolvedRule, error) {
	normalizeRules(st.Rules)
	st.Rules = dropUnspecifiedHosts(st.Rules)
	for i := range st.Rules {
		r := &st.Rules[i]
		if r.Action == "" {
			r.Action = ActionAllow
		}
		if r.Action != ActionAllow {
			return nil, fmt.Errorf("rule %q: action %q: step rules only allow", r.Value, r.Action)
		}
		if r.AutoAddedType != AutoAddedTypeNone {
			return nil, fmt.Errorf("rule %q: autoAddedType is set by cargowall, not by a policy", r.Value)
		}
		// An unknown protocol is dropped when ports are expanded, and a rule
		// left with no ports allows all of them.
		for _, p := range r.Ports {
			switch p.Protocol {
			case ProtocolAll, ProtocolTCP, ProtocolUDP, ProtocolICMP:
			default:
				return nil, fmt.Errorf("rule %q: port %d: unknown protocol %q", r.Value, p.Port, p.Protocol)
			}
		}
	}
	if err := validateRules(st.Rules); err != nil {
		return nil, err
	}
	st.Rules = mergeDuplicateRules(st.Rules)
	resolved := make([]ResolvedRule, 0, len(st.Rules))
	for _, r := range st.Rules {
		rr, err := resolveStepRule(r)
		if err != nil {
			return nil, err
		}
		resolved = append(resolved, rr)
	}
	return resolved, nil
}

// resolveStepRule resolves one normalized step rule. Unlike the job's
// resolveRules, which logs and skips a rule it can't use, a step rule that
// doesn't resolve fails the load. A step's hostname IPs come from the DNS
// path alone, so nothing here touches the job's tracked hostnames.
func resolveStepRule(r Rule) (ResolvedRule, error) {
	rr := ResolvedRule{Type: r.Type, Value: r.Value, Ports: r.Ports, Action: ActionAllow}
	switch r.Type {
	case RuleTypeHostname:
		if r.Value == "" {
			return rr, fmt.Errorf("hostname rule with no value")
		}
		if !isHostnamePattern(r.Value) {
			rr.dotPrefix = "." + r.Value
			return rr, nil
		}
		p, err := compileHostnamePattern(r.Value)
		if err != nil {
			return rr, fmt.Errorf("rule %q: %w", r.Value, err)
		}
		if !hasLiteralLabel(p) {
			return rr, fmt.Errorf("rule %q: a pattern needs a literal label: "+
				"step hostname rules open DNS for every step, and this one matches every name", r.Value)
		}
		rr.Pattern = &p
	case RuleTypeCIDR:
		// normalizeRules made a bare IP an explicit /32 or /128.
		_, ipnet, err := net.ParseCIDR(r.Value)
		if err != nil {
			return rr, fmt.Errorf("rule %q: not a CIDR or an IP address", r.Value)
		}
		rr.IPNet = ipnet
	default:
		return rr, fmt.Errorf("rule %q: unknown type %q", r.Value, r.Type)
	}
	return rr, nil
}

// hasLiteralLabel reports whether a pattern names any label outright. One
// that doesn't (`*`, `**`, `*.*`) matches every name of its depth.
func hasLiteralLabel(p hostnamePattern) bool {
	for _, seg := range p.Segments {
		if seg != "*" && seg != "**" {
			return true
		}
	}
	return false
}

// StepMatch is one step policy whose own rules allow a name.
type StepMatch struct {
	StepID string
	Policy uint32
	// Rule is the allow rule's value (the glob, for a pattern).
	Rule string
	// Ports are the rule's ports; empty means all.
	Ports []Port
}

// MatchStepHostname returns each step policy whose own rules allow
// hostname, in policy order. A step's rules are matched on their own, with
// the precedence and search-domain forms of MatchHostnameRule; the job's
// rules play no part, so callers apply the job's verdict first.
func (cm *Manager) MatchStepHostname(hostname string) []StepMatch {
	cm.mu.RLock()
	defer cm.mu.RUnlock()

	if len(cm.steps) == 0 {
		return nil
	}
	name := strings.ToLower(hostname)
	var out []StepMatch
	for i := range cm.steps {
		sp := &cm.steps[i]
		if _, _, allow := foldForms(cm.matchFormsLocked(sp.rules, name)); allow != nil {
			out = append(out, StepMatch{StepID: sp.id, Policy: sp.policy, Rule: allow.value, Ports: allow.ports})
		}
	}
	return out
}

// StepAllowsHostname reports whether any step's own rules allow hostname:
// MatchStepHostname's question, answered at the first match.
func (cm *Manager) StepAllowsHostname(hostname string) bool {
	cm.mu.RLock()
	defer cm.mu.RUnlock()

	if len(cm.steps) == 0 {
		return false
	}
	name := strings.ToLower(hostname)
	for i := range cm.steps {
		if _, _, allow := foldForms(cm.matchFormsLocked(cm.steps[i].rules, name)); allow != nil {
			return true
		}
	}
	return false
}

// HasStepRules reports whether the loaded policy has a step with rules.
func (cm *Manager) HasStepRules() bool {
	cm.mu.RLock()
	defer cm.mu.RUnlock()
	return len(cm.steps) > 0
}

// StepRulesKnown reports whether the run's step rules are final, and
// whether there are any. A load makes them final (nothing loads a policy
// after startup), and so does SettleStepRules.
func (cm *Manager) StepRulesKnown() (known, has bool) {
	cm.mu.RLock()
	defer cm.mu.RUnlock()
	return cm.steps != nil, len(cm.steps) > 0
}

// SettleStepRules makes the step rules final once startup is done loading:
// a run that loaded no policy (a failed fetch under lockdown, a hook's nil
// policy, a failed file load) has none, so state kept for steps until the
// load (the DNS proxy's via store) is dropped there too. A loaded policy's
// are kept.
func (cm *Manager) SettleStepRules() {
	cm.mu.Lock()
	defer cm.mu.Unlock()
	if cm.steps == nil {
		cm.steps = []stepPolicy{}
	}
}

// JobCIDRDeniesAt returns the ports the job's CIDR deny rules deny at ip
// on, union of every one that contains it, and whether one denies every
// port: what the job's rules still deny there, whatever a step's rules
// allow, since the job decides first. A more specific job allow the
// longest match would pick is not subtracted, so this is the most the job
// can deny there.
func (cm *Manager) JobCIDRDeniesAt(ip net.IP) (ports []Port, all bool) {
	cm.mu.RLock()
	defer cm.mu.RUnlock()
	for _, r := range cm.resolvedRules {
		if r.Type != RuleTypeCIDR || r.Action != ActionDeny || r.IPNet == nil || !r.IPNet.Contains(ip) {
			continue
		}
		if len(r.Ports) == 0 {
			return nil, true
		}
		for _, p := range r.Ports {
			if !slices.Contains(ports, p) {
				ports = append(ports, p)
			}
		}
	}
	return ports, false
}

// DropStepRules gives up the loaded policy's step rules, for why: the hooks
// can't judge a step by its own rules (no step attribution to tell steps
// apart, or a kernel whose verifier rejected the step lookup). Every step
// then gets the job's rules, which fails closed: nothing installs, scopes
// or stamps anything for one. A drop after the load leaves the hooks' step
// lookups in, finding no binding, so whatever binds steps must key off
// HasStepRules, never a collection's gate. It reports whether there were
// any; StepRulesLost keeps why.
func (cm *Manager) DropStepRules(why string) bool {
	cm.mu.Lock()
	defer cm.mu.Unlock()
	if len(cm.steps) == 0 {
		return false
	}
	cm.steps = []stepPolicy{}
	cm.stepsLost = why
	return true
}

// StepRulesLost reports why the loaded policy's step rules were given up,
// or "" when they weren't (DropStepRules).
func (cm *Manager) StepRulesLost() string {
	cm.mu.RLock()
	defer cm.mu.RUnlock()
	return cm.stepsLost
}

// StepPolicy returns the policy the loaded steps give step id, if a step
// with that id has rules. Ids compare without case, as GitHub compares them:
// the load refuses two that differ only in case, so at most one matches.
func (cm *Manager) StepPolicy(id string) (uint32, bool) {
	cm.mu.RLock()
	defer cm.mu.RUnlock()

	for i := range cm.steps {
		if strings.EqualFold(cm.steps[i].id, id) {
			return cm.steps[i].policy, true
		}
	}
	return 0, false
}

// StepRules is one step policy's resolved rules.
type StepRules struct {
	StepID string
	Policy uint32
	Rules  []ResolvedRule
}

// GetStepRules returns each step policy's resolved rules, in policy order.
func (cm *Manager) GetStepRules() []StepRules {
	cm.mu.RLock()
	defer cm.mu.RUnlock()

	out := make([]StepRules, 0, len(cm.steps))
	for _, sp := range cm.steps {
		rules := make([]ResolvedRule, len(sp.rules))
		copy(rules, sp.rules)
		out = append(out, StepRules{StepID: sp.id, Policy: sp.policy, Rules: rules})
	}
	return out
}

// addStepHostnamesLocked adds each literal step hostname to tracked, as an
// allow, where the job doesn't track it already, so startup pre-resolution
// covers step rules too. Patterns are left out, as the job's are. Caller
// must hold cm.mu.
func (cm *Manager) addStepHostnamesLocked(tracked map[string]Action) {
	for _, sp := range cm.steps {
		for _, r := range sp.rules {
			if r.Type != RuleTypeHostname || r.Pattern != nil {
				continue
			}
			if _, ok := tracked[r.Value]; !ok {
				tracked[r.Value] = ActionAllow
			}
		}
	}
}
