func TestValidateSudoersInput(t *testing.T) {
	tests := []struct {
		name      string
		username  string
		cmds      []string
		wantErr   bool
		errSubstr string
	}{
		{
			name:     "valid username and commands",
			username: "runner",
			cmds:     []string{"/usr/bin/kill", "/usr/bin/iptables"},
		},
		{
			name:      "username with space",
			username:  "bad user",
			cmds:      nil,
			wantErr:   true,
			errSubstr: "username",
		},
		{
			name:      "username with semicolon",
			username:  "user;rm",
			cmds:      nil,
			wantErr:   true,
			errSubstr: "username",
		},
		{
			name:      "username with backtick",
			username:  "user`id`",
			cmds:      nil,
			wantErr:   true,
			errSubstr: "username",
		},
		{
			name:      "username with newline",
			username:  "user\nroot ALL=(ALL) ALL",
			cmds:      nil,
			wantErr:   true,
			errSubstr: "username",
		},
		{
			name:      "username with hash",
			username:  "user#comment",
			cmds:      nil,
			wantErr:   true,
			errSubstr: "username",
		},
		{
			name:      "command with space",
			username:  "runner",
			cmds:      []string{"/usr/bin/my command"},
			wantErr:   true,
			errSubstr: "command",
		},
		{
			name:      "command with semicolon",
			username:  "runner",
			cmds:      []string{"/usr/bin/kill;rm -rf /"},
			wantErr:   true,
			errSubstr: "command",
		},
		{
			name:      "empty username returns error",
			username:  "",
			cmds:      []string{"/usr/bin/kill"},
			wantErr:   true,
			errSubstr: "empty",
		},
		{
			name:     "empty commands slice is valid",
			username: "runner",
			cmds:     nil,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := validateSudoersInput(tt.username, tt.cmds)
			if tt.wantErr {
				if err == nil {
					t.Fatal("expected error, got nil")
				}
				if !strings.Contains(err.Error(), tt.errSubstr) {
					t.Errorf("error %q should contain %q", err.Error(), tt.errSubstr)
				}
			} else {
				if err != nil {
					t.Fatalf("unexpected error: %v", err)
				}
			}
		})
	}
}

func TestBuildSudoersConfig(t *testing.T) {
	tests := []struct {
		name         string
		cfg          *SudoLockdownConfig
		username     string
		wantErr      bool
		wantContains []string
		wantAbsent   string
	}{
		{
			name: "single allowed command",
			cfg: &SudoLockdownConfig{
				AllowCommands: []string{"/usr/sbin/iptables"},
			},
			username: "runner",
			wantContains: []string{
				"/usr/sbin/iptables",
				"runner ALL=(ALL) NOPASSWD:",
			},
		},
		{
			name: "multiple allowed commands comma-separated",
			cfg: &SudoLockdownConfig{
				AllowCommands: []string{"/usr/sbin/iptables", "/usr/sbin/ip6tables"},
			},
			username: "runner",
			wantContains: []string{
				"runner ALL=(ALL) NOPASSWD: /usr/sbin/iptables, /usr/sbin/ip6tables",
			},
		},
		{
			name:     "empty allow commands produces only the deny",
			cfg:      &SudoLockdownConfig{},
			username: "runner",
			wantContains: []string{
				"# CargoWall sudo lockdown configuration",
				"\nrunner ALL=(ALL:ALL) !ALL\n",
			},
			wantAbsent: "NOPASSWD",
		},
		{
			name: "unsafe username returns error",
			cfg: &SudoLockdownConfig{
				AllowCommands: []string{"/usr/sbin/iptables"},
			},
			username: "bad;user",
			wantErr:  true,
		},
		{
			name: "output format matches expected sudoers structure",
			cfg: &SudoLockdownConfig{
				AllowCommands: []string{"/usr/sbin/iptables"},
			},
			username: "ci",
			wantContains: []string{
				"# CargoWall sudo lockdown configuration",
				"# Generated by cargowall - DO NOT EDIT",
				"\nci ALL=(ALL:ALL) !ALL\nci ALL=(ALL) NOPASSWD: /usr/sbin/iptables\n",
			},
		},
		{
			name: "header mentions disabled files",
			cfg: &SudoLockdownConfig{
				AllowCommands: []string{"/usr/sbin/iptables"},
			},
			username: "runner",
			wantContains: []string{
				disabledSuffix,
				"sudo-granting groups",
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := buildSudoersConfig(tt.cfg, tt.username)
			if err == nil && !strings.HasSuffix(got, lockdownRules(tt.username, tt.cfg.AllowCommands)) {
				t.Errorf("the file does not end with the lockdown rules:\n%s", got)
			}
			if tt.wantErr {
				if err == nil {
					t.Fatal("expected error, got nil")
				}
				return
			}
			if err != nil {
				t.Fatalf("unexpected error: %v", err)
			}

			for _, s := range tt.wantContains {
				if !strings.Contains(got, s) {
					t.Errorf("output should contain %q\ngot:\n%s", s, got)
				}
			}

			if tt.wantAbsent != "" && strings.Contains(got, tt.wantAbsent) {
				t.Errorf("output should NOT contain %q\ngot:\n%s", tt.wantAbsent, got)
			}
		})
	}
}

// TestLockdownRules_denyFirst: sudoers is last-match-wins, so the deny must
// come before the allowlist or it would take the allowed commands too, and
// it must come at all, or a grant read earlier would still match.
func TestLockdownRules_denyFirst(t *testing.T) {
	got := lockdownRules("runner", []string{"/usr/sbin/iptables", "/usr/sbin/ip6tables"})
	want := "runner ALL=(ALL:ALL) !ALL\nrunner ALL=(ALL) NOPASSWD: /usr/sbin/iptables, /usr/sbin/ip6tables\n"
	if got != want {
		t.Errorf("lockdownRules = %q, want %q", got, want)
	}
	if got := lockdownRules("runner", nil); got != "runner ALL=(ALL:ALL) !ALL\n" {
		t.Errorf("lockdownRules with no allowlist = %q", got)
	}
}

// TestLockdownStateJSONRoundTrip verifies JSON round-trip of lockdownState.
// The real saveLockdownState/loadLockdownState functions use atomic write
// (tmp+rename) and file permissions, which are exercised by the CI
// integration test (test-sudo-lockdown).
func TestLockdownStateJSONRoundTrip(t *testing.T) {
	state := &lockdownState{
		Username:      "runner",
		RemovedGroups: []string{"sudo", "wheel"},
		DisabledFiles: []string{"/etc/sudoers.d/90-runner"},
		DockerRemoved: true,
		SudoersBlock:  true,
	}

	data, err := json.Marshal(state)
	if err != nil {
		t.Fatal(err)
	}

	var loaded lockdownState
	if err := json.Unmarshal(data, &loaded); err != nil {
		t.Fatal(err)
	}

	if loaded.Username != state.Username {
		t.Errorf("username: got %q, want %q", loaded.Username, state.Username)
	}
	if len(loaded.RemovedGroups) != len(state.RemovedGroups) {
		t.Errorf("removedGroups length: got %d, want %d", len(loaded.RemovedGroups), len(state.RemovedGroups))
	}
	if len(loaded.DisabledFiles) != len(state.DisabledFiles) {
		t.Errorf("disabledFiles length: got %d, want %d", len(loaded.DisabledFiles), len(state.DisabledFiles))
	}
	if loaded.DockerRemoved != state.DockerRemoved {
		t.Errorf("dockerRemoved: got %v, want %v", loaded.DockerRemoved, state.DockerRemoved)
	}
	if loaded.SudoersBlock != state.SudoersBlock {
		t.Errorf("sudoersBlock: got %v, want %v", loaded.SudoersBlock, state.SudoersBlock)
	}

	// A state file an earlier version wrote has no sudoersBlock.
	var old lockdownState
	if err := json.Unmarshal([]byte(`{"username":"runner","removedGroups":[],"disabledFiles":[],"dockerRemoved":false}`), &old); err != nil || old.SudoersBlock {
		t.Errorf("an old state file: %+v, %v", old, err)
	}
}

func TestValidateSudoersInput_rejectsWildcards(t *testing.T) {
	// Wildcards in sudoers command paths could grant unintended access
	for _, cmd := range []string{"/usr/bin/*", "/usr/bin/apt?", "/usr/bin/[a-z]"} {
		if err := validateSudoersInput("runner", []string{cmd}); err == nil {
			t.Errorf("expected error for wildcard command %q, got nil", cmd)
		}
	}
}

func TestRecoverLockdownState_findsDisabledFiles(t *testing.T) {
	dir := t.TempDir()
	logger := discardLogger()

	writeFile(t, filepath.Join(dir, "90-runner"+disabledSuffix), "runner ALL=(ALL) ALL\n")
	writeFile(t, filepath.Join(dir, "50-extra"+disabledSuffix), "extra ALL=(ALL) ALL\n")
	writeFile(t, filepath.Join(dir, "normal-file"), "something\n")

	state := recoverLockdownState(dir, filepath.Join(dir, "no-sudoers"), "runner", logger)
	if len(state.DisabledFiles) != 2 {
		t.Errorf("expected 2 disabled files, got %d: %v", len(state.DisabledFiles), state.DisabledFiles)
	}
	if state.Username != "runner" {
		t.Errorf("expected username 'runner', got %q", state.Username)
	}
}

func TestRecoverLockdownState_emptyDir(t *testing.T) {
	dir := t.TempDir()
	logger := discardLogger()

	state := recoverLockdownState(dir, filepath.Join(dir, "no-sudoers"), "runner", logger)
	if len(state.DisabledFiles) != 0 {
		t.Errorf("expected 0 disabled files, got %d", len(state.DisabledFiles))
	}
	if state.SudoersBlock {
		t.Error("recovered a sudoers block from a missing file")
	}
}

func TestRecoverLockdownState_findsSudoersBlock(t *testing.T) {
	dir := t.TempDir()
	main := filepath.Join(t.TempDir(), "sudoers")
	writeFile(t, main, arcSudoers+lockdownBlock(testRules, false))
	if state := recoverLockdownState(dir, main, "runner", discardLogger()); !state.SudoersBlock {
		t.Error("the block in sudoers was not recovered")
	}
	writeFile(t, main, arcSudoers)
	if state := recoverLockdownState(dir, main, "runner", discardLogger()); state.SudoersBlock {
		t.Error("recovered a block from a sudoers without one")
	}
}

// helpers

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func discardLogger() *slog.Logger {
	return slog.New(slog.NewTextHandler(io.Discard, nil))
}
